/// Consistent spacing scale based on multiples of 4.
/// Use these instead of magic numbers in EdgeInsets / SizedBox.
class AppSpacing {
  AppSpacing._();

  static const double xs = 4.0;
  static const double sm = 8.0;
  static const double md = 12.0;
  static const double lg = 16.0;
  static const double xl = 24.0;
  static const double xxl = 32.0;
  static const double huge = 48.0;
  static const double massive = 60.0;

  /// Horizontal page padding used across onboarding screens.
  static const double pageHorizontal = 26.0;

  /// Common vertical gaps
  static const double section = 32.0;
  static const double chipGap = 8.0;
  static const double rowGap = 8.0;
}
